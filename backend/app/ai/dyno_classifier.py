def _width_profile_residual(
    normalised: np.ndarray,
    load: np.ndarray,
    rising: np.ndarray,
    falling: np.ndarray,
    span: float,
    bins: int = 16,
) -> float:
    r"""Departure of the card loop from a constant-width parallelogram.

    The card is divided into ``bins`` slices of plunger position.  In each
    slice that contains samples from both strokes, the mean downstroke load less
    the mean upstroke load gives the local width :math:`w(u)`.  A healthy card
    has :math:`w` close to a straight line in :math:`u`, because the travelling
    valve loads the two strokes by about the same amount everywhere; rod float
    adds a localised mid-downstroke depression, which bows the profile.

    The returned value is the RMS departure from the best-fit line, normalised by
    the load span so it is independent of amplitude.

    Binning is on position rather than on time because the Gibbs solver re-phases
    the card, so sample order is arbitrary but matched positions are not.  Bins
    that fall on a turnaround and contain only one stroke are skipped, and a card
    with too few usable bins returns ``0.0`` rather than raising.
    """
    if span <= 0.0:
        return 0.0
    # ``rising``/``falling`` are differences, so they index the interval
    # [i, i+1]; attribute each to its left-hand sample's position.
    up_mask = np.zeros_like(normalised, dtype=bool)
    down_mask = np.zeros_like(normalised, dtype=bool)
    up_mask[:-1] |= rising
    down_mask[:-1] |= falling
    up_mask[1:] |= rising
    down_mask[1:] |= falling

    centres: List[float] = []
    widths: List[float] = []
    for index in range(bins):
        centre = (index + 0.5) / bins
        selection = np.abs(normalised - centre) < (0.6 / bins)
        up = selection & up_mask
        down = selection & down_mask
        if not up.any() or not down.any():
            continue
        centres.append(centre)
        widths.append(float(np.mean(load[down]) - np.mean(load[up])))

    if len(centres) < 4:
        return 0.0
    x = np.asarray(centres, dtype=float)
    y = np.asarray(widths, dtype=float)
    slope, intercept = np.polyfit(x, y, 1)
    residual = y - (slope * x + intercept)
    return float(np.sqrt(np.mean(residual**2)) / span)


def card_features(position_m: Sequence[float], load_n: Sequence[float]) -> Dict[str, float]:
    """Geometric features of a card, used by the analytic cross-check.

    The features encode the four physical diagnostics an analyst reads off a
    card:

    ``upstroke_reversal``
        Fraction of the upstroke over which the load *falls* while the plunger
        rises.  Physically impossible in steady pumping, and the definitive
        fluid-pound signature.
    ``downstroke_asymmetry``
        Departure of the card loop from a *constant-width* parallelogram,
        normalised by the load span.  A healthy card is a loop of roughly
        constant width -- the travelling valve makes the upstroke heavier than
        the downstroke by about the same amount at every position -- so its
        width profile is straight.  Buoyant drag on the downstroke is instead a
        localised depression at mid-downstroke, so the width profile is bumpy.
        This is the rod-float signature.

        The name is retained from the earlier mean-difference definition for
        contract compatibility: the ten feature keys are pinned by
        ``backend/tests/test_api_stream.py::FEATURE_KEYS`` and read by name in
        ``frontend/src/components/DynoCardCanvas.tsx``.  The *meaning* changed
        when the generator was corrected to emit a real parallelogram, because
        the mean difference alone cannot separate a healthy loop's width from a
        floating rod's depression.
    ``tail_spike``
        Load excess at the end of the downstroke, i.e. a mechanical impact.
    ``linearity``
        RMS departure of the card from a straight-sided parallelogram.  A
        cushioning gas cap rounds the card, so a non-parallelogram shape with
        none of the specific faults present is gas interference.
    ``skew``
        Displacement of the load maximum from top dead centre, which is the
        unanchored-tubing signature.
    """
    position = np.asarray(position_m, dtype=float)
    load = np.asarray(load_n, dtype=float)
    if position.ndim != 1 or load.ndim != 1 or len(position) != len(load):
        raise ValueError("position and load must be one-dimensional and equal length")
    if len(position) < 8:
        raise ValueError("at least eight card samples are required")

    stroke = float(np.max(position) - np.min(position))
    if stroke <= 0.0:
        raise ValueError("card has zero stroke")
    normalised = (position - float(np.min(position))) / stroke
    load_min = float(np.min(load))
    load_max = float(np.max(load))
    span = load_max - load_min
    if span <= 0.0:
        span = 1.0
    unit = (load - load_min) / span

    rising = normalised[1:] > normalised[:-1]
    falling = normalised[1:] < normalised[:-1]

    # Fluid pound: the load must rise with the plunger on the upstroke.  The
    # comparison is made on a smoothed trace, because load-cell noise alone
    # produces a negative increment on almost every sample and would otherwise
    # swamp the physical reversal.
    # The smoothing window is chosen long compared with a cushioning ripple
    # period so that the oscillation is attenuated before the derivative is
    # taken, while the sustained collapse of a fluid-pound upstroke survives.
    window = max(5, int(round(len(load) / 12)) | 1)
    smooth = np.convolve(unit, np.ones(window) / window, mode="same")
    offset = max(1, window // 2)
    sustained_drop = np.zeros_like(smooth)
    if len(smooth) > offset:
        sustained_drop[:-offset] = smooth[:-offset] - smooth[offset:]

    # Exclude the two turnarounds (bottom and top dead centre) before taking the
    # maximum.  A healthy card is a *parallelogram*: the standing valve makes the
    # upstroke and downstroke carry different column weights, so the load steps
    # at each reversal.  That step is geometry, not a fault, and measuring the
    # smoothed derivative across it would read every healthy card as fluid
    # pound.  Only the interior of the upstroke, where a genuine supply collapse
    # makes the load fall while the plunger is still rising, is a signal.
    turnarounds = np.zeros_like(rising)
    half = max(1, window)
    rising_index = np.flatnonzero(rising)
    falling_index = np.flatnonzero(falling)
    if rising_index.size and falling_index.size:
        for boundary in (int(rising_index[-1]) + 1, int(falling_index[-1]) + 1):
            if 0 < boundary < len(turnarounds):
                turnarounds[max(0, boundary - half) : min(len(turnarounds), boundary + half)] = True
    interior_rising = rising & ~turnarounds
    reversal = (
        float(np.max(sustained_drop[1:][interior_rising])) if np.any(interior_rising) else 0.0
    )
    reversal = min(max(reversal, 0.0), 1.0)

    # Rod float: departure of the loop from a constant-width parallelogram.
    #
    # Binning by *position* (not by sample index) is what makes this work: the
    # Gibbs solver re-phases the card onto bottom dead centre, so sample order
    # carries no meaning, but matched positions on the two strokes do.
    #
    # A healthy card is a loop of roughly constant width, so the width profile
    # is straight.  Buoyant drag is a depression localised at mid-downstroke, so
    # the profile is bumpy -- and that shape difference survives any loop width,
    # which the plain mean difference could not: a healthy card and a floating
    # rod differ in *how the width varies*, not merely in how wide it is.
    width_profile = _width_profile_residual(normalised, load, rising, falling, span)
    asymmetry = width_profile

    # Pump tagging: excess load at the end of the downstroke.
    end = max(2, len(load) // 25)
    tail = float(np.max(unit[-end:]) - np.mean(unit[-end:]))

    # Gas interference.  A cushioning gas cap produces a *coherent* ripple,
    # whereas load-cell noise is white, so the lag-1 autocorrelation of the
    # detrended load separates the two far more cleanly than its amplitude.
    kernel = np.ones(window) / window
    smoothed = np.convolve(load, kernel, mode="same")
    residual = load - smoothed
    ripple = float(np.std(residual) / span)
    energy = float(np.mean(residual**2))
    if energy > 0.0:
        coherence = float(np.mean(residual[1:] * residual[:-1]) / energy)
    else:
        coherence = 0.0

    # Linearity of the card.  A healthy pump, an unanchored tubing and a
    # mechanical impact all trace a straight-sided parallelogram in
    # (position, load), whereas a cushioning gas cap and a collapsing fluid
    # column do not.  This is the residual discriminator once the specific
    # faults have been ruled out.
    slope, intercept = np.polyfit(normalised, unit, 1)
    residual_fit = unit - (slope * normalised + intercept)
    linearity = float(np.sqrt(np.mean(residual_fit**2)))

    # Unanchored tubing: the load maximum is displaced from top dead centre.
    skew = float(normalised[int(np.argmax(load))] - 1.0)

    return {
        "stroke_m": stroke,
        "load_span_n": span,
        "upstroke_reversal": reversal,
        "downstroke_asymmetry": asymmetry,
        "tail_spike": tail,
        "ripple": ripple,
        "coherence": coherence,
        "linearity": linearity,
        "skew": skew,
        "top_position_fraction": float(normalised[int(np.argmax(load))]),
    }


def analytic_diagnosis(features: Dict[str, float]) -> CardLabel:
    """Rule-based diagnosis from the geometric card features.

    Independent of the network and computed from the same features, so that
    agreement between the two is a genuine cross-check rather than a tautology.
    The order follows the physical hierarchy: a hard mechanical impact outranks
    a fluid-supply problem, which outranks a supply problem.
    """
    if features["tail_spike"] > 0.18:
        return CardLabel.PUMP_TAGGING
    if features["upstroke_reversal"] > 0.10:
        return CardLabel.FLUID_POUND
    # Rod float depresses the *downstroke*, so the downstroke mean falls below
    # the upstroke mean.  Unanchored tubing lags the load, which raises it.
    # The sign of the asymmetry therefore separates the two.
    if features["downstroke_asymmetry"] < -0.08:
        return CardLabel.ROD_FLOATING
    if features["downstroke_asymmetry"] > 0.15:
        return CardLabel.UNANCHORED_TUBING
    if features["linearity"] > 0.06:
        return CardLabel.GAS_INTERFERENCE
    return CardLabel.NORMAL_FULL_BARREL


