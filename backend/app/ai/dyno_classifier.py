#: Number of samples in the normalised card representation.
CARD_LENGTH = 128
#: Number of crank cycles generated by the parametric card model.
SAMPLES_PER_CARD = 512


class CardLabel(str, Enum):
    """Operational states recognised by the classifier."""

    NORMAL_FULL_BARREL = "NORMAL_FULL_BARREL"
    FLUID_POUND = "FLUID_POUND"
    ROD_FLOATING = "ROD_FLOATING"
    GAS_INTERFERENCE = "GAS_INTERFERENCE"
    PUMP_TAGGING = "PUMP_TAGGING"
    UNANCHORED_TUBING = "UNANCHORED_TUBING"


CARD_LABELS: Tuple[CardLabel, ...] = tuple(CardLabel)
LABEL_INDEX: Dict[CardLabel, int] = {label: i for i, label in enumerate(CARD_LABELS)}


