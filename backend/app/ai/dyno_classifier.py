def _build_net():
    """Construct the residual 1D CNN.  Separated so torch is imported lazily."""
    torch = _torch()
    import torch.nn as nn

    class _ResidualBlock(nn.Module):
        """Two dilated convolutions with a residual connection."""

        def __init__(self, channels: int, dilation: int) -> None:
            super().__init__()
            self.conv1 = nn.Conv1d(
                channels, channels, kernel_size=5, padding=2 * dilation, dilation=dilation
            )
            self.conv2 = nn.Conv1d(channels, channels, kernel_size=5, padding=2, dilation=1)
            self.norm1 = nn.BatchNorm1d(channels)
            self.norm2 = nn.BatchNorm1d(channels)
            self.activation = nn.GELU()

        def forward(self, x):
            residual = x
            out = self.activation(self.norm1(self.conv1(x)))
            out = self.norm2(self.conv2(out))
            return self.activation(out + residual)

    class Network(nn.Module):
        """Residual 1D CNN over the (position, load) card channels."""

        def __init__(self, classes: int = len(CARD_LABELS), width: int = 32) -> None:
            super().__init__()
            self.stem = nn.Sequential(
                nn.Conv1d(2, width, kernel_size=7, padding=3),
                nn.BatchNorm1d(width),
                nn.GELU(),
            )
            self.blocks = nn.Sequential(
                _ResidualBlock(width, dilation=1),
                _ResidualBlock(width, dilation=2),
                _ResidualBlock(width, dilation=4),
            )
            self.head = nn.Sequential(
                nn.AdaptiveAvgPool1d(1),
                nn.Flatten(),
                nn.Linear(width, width),
                nn.GELU(),
                nn.Dropout(0.1),
                nn.Linear(width, classes),
            )

        def forward(self, x):
            features = self.blocks(self.stem(x))
            return self.head(features)

    return Network()


