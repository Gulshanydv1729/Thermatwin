"""Dynamometer card fault classification with a 1D convolutional network.

Six operational states of a sucker rod pump are distinguished from the
reconstructed downhole card:

===========================  ==========================================
Label                        Physical signature
===========================  ==========================================
``NORMAL_FULL_BARREL``       Full-barrel parallelogram, 100% fillage.
``FLUID_POUND``              Inflow below pump displacement: the load
                             collapses over the un-filled part of the
                             upstroke and a late impact follows.
``ROD_FLOATING``             Buoyant viscous drag on the downstroke drives
                             the load below rod weight, into compression.
``GAS_INTERFERENCE``         A compressed gas cap cushions the card: small
                             amplitude, rounded corners, high ripple.
``PUMP_TAGGING``             The plunger meets a stop, giving a load spike
                             at the end of the downstroke.
``UNANCHORED_TUBING``        Skewed parallelogram: the load extrema are
                             displaced from top and bottom dead centre.
===========================  ==========================================

The network is a residual 1D CNN over the ``(position, load)`` sequence, which
is normalised to a fixed-length resampling so that cards from different SPM
and stroke settings share one representation.  Training data is generated by a
parametric forward model of the surface card, so the routine on
:func:`ensure_weights` can bootstrap the network from first principles when no
cached weights are present.
"""

