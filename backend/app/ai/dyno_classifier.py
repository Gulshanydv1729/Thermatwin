@dataclass
class CardPrediction:
    """Outcome of a single card classification."""

    label: CardLabel
    confidence: float
    probabilities: Dict[str, float]
    features: Dict[str, float]
    analytic_label: CardLabel

    @property
    def agrees_with_analytic(self) -> bool:
        """Whether the network and the geometric cross-check agree."""
        return self.label is self.analytic_label

    def as_dict(self) -> dict:
        """JSON-serialisable view for the API layer."""
        return {
            "label": self.label.value,
            "confidence": self.confidence,
            "probabilities": dict(self.probabilities),
            "features": dict(self.features),
            "analytic_label": self.analytic_label.value,
            "agrees_with_analytic": self.agrees_with_analytic,
        }


class DynoCardClassifier:
    """Trained residual 1D CNN wrapper with persistence and analytic cross-check.

    Parameters
    ----------
    weights_path
        Where the trained weights are cached.  If the file is absent the
        network is trained on synthetic cards and the result written here.
    device
        Torch device string; ``"cpu"`` is used for the in-cluster deployment.
    seed
        Seed for reproducible initialisation and training.
    """

    def __init__(
        self,
        weights_path: Optional[Path] = None,
        device: str = "cpu",
        seed: int = 26120,
        train: bool = True,
    ) -> None:
        self.weights_path = Path(weights_path) if weights_path else None
        self.device = device
        self.seed = seed
        torch = _torch()
        torch.manual_seed(seed)
        self.net = _build_net().to(device)
        self.net.eval()
        self.trained = False
        if train and self.weights_path is not None and self.weights_path.exists():
            self.load()
        elif train:
            self.train_and_save(self.weights_path)

    # -- persistence ------------------------------------------------------
    def save(self, path: Optional[Path] = None) -> Path:
        """Write the weights to ``path`` (or the configured path)."""
        target = Path(path) if path else self.weights_path
        if target is None:
            raise ValueError("no weights path configured")
        target.parent.mkdir(parents=True, exist_ok=True)
        torch = _torch()
        torch.save({"state_dict": self.net.state_dict(), "seed": self.seed}, target)
        return target

    def load(self, path: Optional[Path] = None) -> None:
        """Read weights from ``path`` (or the configured path)."""
        source = Path(path) if path else self.weights_path
        if source is None or not source.exists():
            raise FileNotFoundError("no trained weights available")
        torch = _torch()
        payload = torch.load(source, map_location=self.device, weights_only=True)
        self.net.load_state_dict(payload["state_dict"])
        self.net.eval()
        self.trained = True

    # -- training ---------------------------------------------------------
    def train_and_save(
        self,
        path: Optional[Path] = None,
        epochs: int = 26,
        batch_size: int = 64,
        samples_per_label: int = 700,
        validation_fraction: float = 0.15,
        damping_rates: Optional[Sequence[float]] = None,
    ) -> Dict[str, float]:
        """Train the network on synthetic cards and persist the weights.

        The set is split deterministically into training and validation
        partitions, and the returned metrics include the validation accuracy
        and the per-class recall, which the test suite asserts on.

        Parameters
        ----------
        damping_rates
            Sequence of damping rates used to reconstruct surface cards to
            downhole cards during training. If None, a default range covering
            cool to hot reservoir conditions is used. This trains the network
            to be robust across the full operating envelope.
        """
        torch = _torch()
        inputs, targets = build_training_set(
            samples_per_label=samples_per_label, seed=self.seed, damping_rates=damping_rates
        )
        rng = np.random.default_rng(self.seed)
        order = rng.permutation(len(inputs))
        inputs, targets = inputs[order], targets[order]
        split = int(len(inputs) * (1.0 - validation_fraction))
        train_x = torch.from_numpy(inputs[:split])
        train_y = torch.from_numpy(targets[:split])
        val_x = torch.from_numpy(inputs[split:])
        val_y = torch.from_numpy(targets[split:])

        optimiser = torch.optim.AdamW(self.net.parameters(), lr=3e-3, weight_decay=1e-4)
        criterion = torch.nn.CrossEntropyLoss()
        generator = torch.Generator().manual_seed(self.seed)
        loader = torch.utils.data.DataLoader(
            torch.utils.data.TensorDataset(train_x, train_y),
            batch_size=batch_size,
            shuffle=True,
            generator=generator,
        )
        self.net.train()
        last_loss = 0.0
        for _ in range(epochs):
            for batch_x, batch_y in loader:
                optimiser.zero_grad()
                loss = criterion(self.net(batch_x.to(self.device)), batch_y.to(self.device))
                loss.backward()
                optimiser.step()
                last_loss = float(loss.item())
        self.net.eval()

        with torch.no_grad():
            logits = self.net(val_x.to(self.device))
            predictions = logits.argmax(dim=1).cpu().numpy()
        expected = val_y.numpy()
        accuracy = float(np.mean(predictions == expected))
        recall: Dict[str, float] = {}
        for label in CARD_LABELS:
            index = LABEL_INDEX[label]
            mask = expected == index
            recall[label.value] = float(np.mean(predictions[mask] == expected[mask])) if np.any(mask) else 0.0
        metrics = {"validation_accuracy": accuracy, "final_loss": last_loss, **recall}
        self.metrics = metrics
        self.trained = True
        if path is not None or self.weights_path is not None:
            self.save(path)
        return metrics

    # -- inference --------------------------------------------------------
    def predict(
        self,
        position_m: Sequence[float],
        load_n: Sequence[float],
    ) -> CardPrediction:
        """Classify a single card and return the label with its confidence."""
        if not self.trained:
            raise RuntimeError("classifier has not been trained")
        torch = _torch()
        features = card_features(position_m, load_n)
        batch = torch.from_numpy(normalise_card(position_m, load_n)[None, ...]).to(self.device)
        with torch.no_grad():
            logits = self.net(batch)
            probabilities = torch.softmax(logits, dim=1)[0].cpu().numpy()
        index = int(np.argmax(probabilities))
        return CardPrediction(
            label=CARD_LABELS[index],
            confidence=float(probabilities[index]),
            probabilities={
                label.value: float(probabilities[i]) for i, label in enumerate(CARD_LABELS)
            },
            features=features,
            analytic_label=analytic_diagnosis(features),
        )

    def predict_batch(
        self, positions: Sequence[Sequence[float]], loads: Sequence[Sequence[float]]
    ) -> List[CardPrediction]:
        """Classify a batch of cards, batching the network forward pass."""
        if not self.trained:
            raise RuntimeError("classifier has not been trained")
        if len(positions) != len(loads):
            raise ValueError("positions and loads must have the same batch length")
        torch = _torch()
        if not positions:
            return []
        batch = np.stack([normalise_card(p, l) for p, l in zip(positions, loads)])
        with torch.no_grad():
            logits = self.net(torch.from_numpy(batch).to(self.device))
            probabilities = torch.softmax(logits, dim=1).cpu().numpy()
        results: List[CardPrediction] = []
        for i, (position, load) in enumerate(zip(positions, loads)):
            index = int(np.argmax(probabilities[i]))
            features = card_features(position, load)
            results.append(
                CardPrediction(
                    label=CARD_LABELS[index],
                    confidence=float(probabilities[i][index]),
                    probabilities={
                        label.value: float(probabilities[i][j])
                        for j, label in enumerate(CARD_LABELS)
                    },
                    features=features,
                    analytic_label=analytic_diagnosis(features),
                )
            )
        return results


def ensure_weights(
    weights_dir: Path,
    device: str = "cpu",
    seed: int = 26120,
    epochs: int = 26,
    samples_per_label: int = 700,
    damping_rates: Optional[Sequence[float]] = None,
) -> DynoCardClassifier:
    """Load cached weights, or train and cache them on first use.

    This is the on-boot routine: a fresh deployment trains from the
    parametric card model and writes the weights, so no binary checkpoint has
    to be committed.
    """
    target = Path(weights_dir) / "dyno_classifier.pt"
    classifier = DynoCardClassifier(weights_path=target, device=device, seed=seed, train=False)
    if target.exists():
        classifier.load()
        return classifier
    classifier.train_and_save(
        target, epochs=epochs, samples_per_label=samples_per_label, damping_rates=damping_rates
    )
    return classifier
