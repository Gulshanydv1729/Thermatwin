def synthesize_card(
    label: CardLabel,
    rod_weight_n: float = 21937.6,
    fluid_load_n: float = 26000.0,
    stroke_m: float = PUMPING_UNIT.nominal_stroke_m,
    fillage: float = 1.0,
    samples: int = SAMPLES_PER_CARD,
    noise_fraction: float = 0.01,
    seed: Optional[int] = None,
    valve_width_fraction: float = 0.25,
) -> Tuple[np.ndarray, np.ndarray]:
    r"""Generate a synthetic surface dynamometer card for ``label``.

    The card is built from the standard sucker rod pump construction.  The
    polished rod position over a crank cycle is, to a very good approximation,
    sinusoidal,

    .. math:: x(\theta) = \frac{L_s}{2}(1 - \cos\theta),

    and the surface load is the rod weight plus the fluid column load.  On the
    upstroke the pump fills and the fluid load grows roughly linearly with
    position, which is what produces the familiar parallelogram; on the
    downstroke the column unloads along the same line.

    Parameters
    ----------
    label
        Target state, which selects the deformation applied to the ideal card.
    rod_weight_n
        Weight of the rod string, N.
    fluid_load_n
        Load of a full fluid column, N.
    stroke_m
        Stroke length, m.
    fillage
        Pump fillage in [0, 1]; below 1 the barrel does not fill and the
        classic fluid pound develops.
    samples
        Number of samples in the returned card.
    noise_fraction
        Standard deviation of the additive load noise, as a fraction of the
        load span.
    seed
        Optional seed for the noise, for reproducible training sets.
    valve_width_fraction
        Width of the card loop as a fraction of the full fluid load, i.e. how
        much heavier the upstroke is than the downstroke.  Zero produces a
        single line, which is not what a real pump traces; the working range is
        roughly 0.10 to 0.45.

    Returns
    -------
    (position_m, load_n)
        The card, as float arrays of length ``samples``.
    """
    if samples < 32:
        raise ValueError("at least 32 samples are required")
    if not 0.0 < fillage <= 1.0:
        raise ValueError("fillage must lie in (0, 1]")
    if rod_weight_n <= 0.0 or fluid_load_n <= 0.0:
        raise ValueError("rod weight and fluid load must be positive")
    if valve_width_fraction < 0.0:
        raise ValueError("valve_width_fraction must be non-negative")

    rng = np.random.default_rng(seed)
    crank = np.linspace(0.0, 2.0 * math.pi, samples, endpoint=False)
    # Polished rod position: 0 at bottom dead centre, stroke at top dead centre.
    position = 0.5 * stroke_m * (1.0 - np.cos(crank))
    normalised = position / stroke_m          # 0..1 across the stroke
    upstroke = crank < math.pi                 # position rising
    load = np.full(samples, rod_weight_n, dtype=float)

    # Travelling-valve differential, applied to every label.  The standing valve
    # admits fluid while the plunger rises and the travelling valve expels it
    # while the plunger falls, so the two strokes never carry the same column
    # weight.  This width is what makes the card a *parallelogram* rather than a
    # single line: without it the load is a pure function of position and both
    # strokes trace the same curve.  It scales with the volume swept, so the
    # width is zero at bottom dead centre and widest at top dead centre.
    valve_width = valve_width_fraction * fluid_load_n * np.clip(normalised, 0.0, 1.0)
    load += np.where(upstroke, valve_width, -valve_width)

    if label is CardLabel.NORMAL_FULL_BARREL:
        # Full barrel: the fluid load follows the swept volume exactly and the
        # loop keeps a constant width, so the card is a straight-sided
        # parallelogram.  This is the reference shape every other fault
        # deforms.
        load += fluid_load_n * np.clip(normalised, 0.0, 1.0)

    elif label is CardLabel.FLUID_POUND:
        # The plunger displaces more fluid than the formation supplies, so after
        # the barrel has filled at ``fillage`` of the stroke the column can no
        # longer support the rod and the load *falls* while the plunger is still
        # rising.  A load that decreases with rising position is the defining
        # fluid-pound signature.
        filled = np.clip(normalised / max(fillage, 1e-6), 0.0, 1.0)
        drained = np.where(
            upstroke,
            np.clip((normalised - fillage) / max(1.0 - fillage, 1e-6), 0.0, 1.0),
            0.0,
        )
        load += fluid_load_n * (filled - 0.95 * drained)

    elif label is CardLabel.ROD_FLOATING:
        # Buoyant viscous drag on the downstroke: the descending rod column is
        # buoyed by the fluid, so the surface load is depressed through the
        # middle of the downstroke and can pass below the rod weight.  The drag
        # bump is a genuine function of crank angle, not a phase mask, so it
        # varies *along* the downstroke.
        load += fluid_load_n * np.clip(normalised, 0.0, 1.0)
        drag_bump = np.exp(-(((crank - 1.55 * math.pi) / 0.42) ** 2))
        load -= 1.15 * fluid_load_n * drag_bump

    elif label is CardLabel.GAS_INTERFERENCE:
        # A compressed gas cap is compressed further as the plunger enters, so
        # it cushions the load: the span collapses and the trace gains ripple.
        cushion = 0.45 + 0.55 * np.clip(normalised, 0.0, 1.0)
        load += fluid_load_n * cushion * np.clip(normalised, 0.0, 1.0)
        load += fluid_load_n * 0.16 * np.sin(11.0 * crank)

    elif label is CardLabel.PUMP_TAGGING:
        # The plunger meets a mechanical stop at the end of the downstroke.
        load += fluid_load_n * np.clip(normalised, 0.0, 1.0)
        impact = np.exp(-(((crank - 1.97 * math.pi) / 0.045) ** 2))
        load += 1.30 * fluid_load_n * impact

    elif label is CardLabel.UNANCHORED_TUBING:
        # The tubing is not anchored, so the load extrema lag the dead centres
        # by a fixed crank offset: a skewed parallelogram.
        lagged = np.mod(crank - 1.05, 2.0 * math.pi)
        skewed = np.clip(0.5 * (1.0 - np.cos(lagged)), 0.0, 1.0)
        load += fluid_load_n * skewed

    else:  # pragma: no cover - exhaustive over the enum
        raise ValueError(f"unknown card label {label!r}")

    if noise_fraction > 0.0:
        span = float(np.max(load) - np.min(load)) or 1.0
        load = load + rng.normal(0.0, noise_fraction * span, samples)

    return position, load


def build_training_set(
    samples_per_label: int = 900,
    seed: int = 26120,
    samples: int = SAMPLES_PER_CARD,
    damping_rates: Optional[Sequence[float]] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """Generate a labelled training set from the parametric card model.

    Each class is drawn over a randomised operating envelope (stroke, fillage,
    noise, rod and fluid loads) so the network cannot latch onto a single
    amplitude.

    The synthetic surface cards are passed through the Gibbs solver with varying
    damping rates to produce downhole cards, matching the inference-time
    distribution shift caused by rod-string damping across different reservoir
    temperatures.

    Returns
    -------
    (inputs, targets)
        ``inputs`` has shape ``(n, 2, CARD_LENGTH)`` (position and load
        channels, normalised); ``targets`` has shape ``(n,)`` of int64 labels.
    """
    # Import here to avoid circular dependency at module load time
    from backend.app.physics.gibbs_solver import GibbsSolver, baghewala_rod_string

    if damping_rates is None:
        # Range of damping rates covering cool (high viscosity) to hot (low viscosity)
        damping_rates = [0.05, 0.10, 0.15, 0.20, 0.25, 0.30]

    rng = np.random.default_rng(seed)
    inputs: List[np.ndarray] = []
    targets: List[int] = []
    rod = baghewala_rod_string()
    for label in CARD_LABELS:
        for _ in range(samples_per_label):
            stroke = float(rng.uniform(1.8, 3.0))
            if label is CardLabel.FLUID_POUND:
                fillage = float(rng.uniform(0.35, 0.85))
            elif label is CardLabel.ROD_FLOATING:
                fillage = float(rng.uniform(0.85, 1.0))
            else:
                fillage = float(rng.uniform(0.92, 1.0))
            rod_weight = float(rng.uniform(15000.0, 30000.0))
            fluid_load = float(rng.uniform(12000.0, 45000.0))
            noise = float(rng.uniform(0.002, 0.03))
            # The card loop width, spanning the plausible range for the
            # travelling-valve differential.  The network must learn every
            # width, not one, or it will latch onto an amplitude instead of a
            # shape and misread a well with a different valve as faulty.
            valve_width_fraction = float(rng.uniform(0.10, 0.45))
            position, load = synthesize_card(
                label,
                rod_weight_n=rod_weight,
                fluid_load_n=fluid_load,
                stroke_m=stroke,
                fillage=fillage,
                samples=samples,
                noise_fraction=noise,
                seed=int(rng.integers(0, 2**31 - 1)),
                valve_width_fraction=valve_width_fraction,
            )
            # Reconstruct to downhole card with random damping to match inference distribution
            damping = float(rng.choice(damping_rates))
            solver = GibbsSolver(rod=rod, segments=40, damping_rate_s=damping)
            card = solver.solve(
                surface_position_m=position,
                surface_load_n=load,
                duration_s=60.0 / 9.0,  # nominal SPM cycle duration
            )
            normalised = normalise_card(card.position_m, card.load_n, samples=CARD_LENGTH)
            inputs.append(normalised)
            targets.append(LABEL_INDEX[label])
    return np.asarray(inputs, dtype=np.float32), np.asarray(targets, dtype=np.int64)


def normalise_card(
    position_m: Sequence[float], load_n: Sequence[float], samples: int = CARD_LENGTH
) -> np.ndarray:
    """Resample and normalise a card into a ``(2, samples)`` network input.

    Position is scaled to ``[-1, 1]`` over the observed stroke and load to
    zero mean and unit standard deviation, so the network sees shape rather
    than absolute magnitude.

    Raises
    ------
    ValueError
        If the card is shorter than ``samples`` or is not finite.
    """
    position = np.asarray(position_m, dtype=float)
    load = np.asarray(load_n, dtype=float)
    if position.ndim != 1 or load.ndim != 1:
        raise ValueError("card inputs must be one-dimensional")
    if len(position) != len(load):
        raise ValueError("position and load must have the same length")
    if len(position) < 8:
        raise ValueError("at least eight card samples are required")
    if not np.all(np.isfinite(position)) or not np.all(np.isfinite(load)):
        raise ValueError("card contains non-finite values")

    source = np.linspace(0.0, 1.0, len(position))
    target = np.linspace(0.0, 1.0, samples)
    resampled_position = np.interp(target, source, position)
    resampled_load = np.interp(target, source, load)

    stroke = float(np.max(resampled_position) - np.min(resampled_position))
    if stroke <= 0.0:
        raise ValueError("card has zero stroke")
    centre = 0.5 * (float(np.max(resampled_position)) + float(np.min(resampled_position)))
    scaled_position = (resampled_position - centre) / (0.5 * stroke)

    spread = float(np.std(resampled_load))
    if spread <= 0.0:
        spread = 1.0
    scaled_load = (resampled_load - float(np.mean(resampled_load))) / spread

    return np.stack([scaled_position, scaled_load]).astype(np.float32)


